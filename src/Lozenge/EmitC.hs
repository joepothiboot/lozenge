{-# LANGUAGE OverloadedStrings #-}

module Lozenge.EmitC (
  emitC,
)
where

import Control.Monad (unless, zipWithM_)
import Data.Text (Text)
import Data.Text qualified as T
import Lozenge.Fusion (Buf (..), Ew (..), Kernel (..), Program (..))

emitC :: Program -> Either Text Text
emitC p = do
  checkProgram p
  outSize <- bufSize p (length (progKernels p)) (progOutput p)
  pure . T.unlines $
    [ "/* Generated by lozenge. */",
      "#include <stdio.h>",
      "#include <stdlib.h>",
      ""
    ]
      <> zipWith (\i (_, n) -> array (buf (InBuf i)) n) [0 ..] (progInputs p)
      <> zipWith (\i k -> array (buf (TmpBuf i)) (kernelSize k)) [0 ..] (progKernels p)
      <> [""]
      <> concat (zipWith kernelFn [0 ..] (progKernels p))
      <> (if null (progInputs p) then [] else readInput)
      <> ["int main(void) {"]
      <> zipWith (\i (_, n) -> "  read_input(" <> buf (InBuf i) <> ", " <> showT n <> ");") [0 ..] (progInputs p)
      <> zipWith (\i _ -> "  kernel" <> showT i <> "();") [0 :: Int ..] (progKernels p)
      <> [ "  for (long i = 0; i < " <> showT outSize <> "; i++) printf(\"%.17g\\n\", " <> buf (progOutput p) <> "[i]);",
           "  return 0;",
           "}"
         ]

array :: Text -> Int -> Text
array name n = "static double " <> name <> "[" <> showT (max 1 n) <> "];"

readInput :: [Text]
readInput =
  [ "static void read_input(double *buf, long n) {",
    "  for (long i = 0; i < n; i++) {",
    "    if (scanf(\"%lf\", &buf[i]) != 1) {",
    "      fprintf(stderr, \"lozenge: not enough input numbers\\n\");",
    "      exit(2);",
    "    }",
    "  }",
    "}",
    ""
  ]

kernelFn :: Int -> Kernel -> [Text]
kernelFn i k =
  ["/* kernel " <> showT i <> ": " <> describe k <> " */", "static void kernel" <> showT i <> "(void) {"]
    <> map ("  " <>) (body k)
    <> ["}", ""]
  where
    out = buf (TmpBuf i)
    body (Elementwise n e) =
      ["for (long i = 0; i < " <> showT n <> "; i++) " <> out <> "[i] = " <> ew e <> ";"]
    body (MatMulK a b m kk n) =
      [ "for (long i = 0; i < " <> showT m <> "; i++) {",
        "  for (long j = 0; j < " <> showT n <> "; j++) {",
        "    double acc = 0.0;",
        "    for (long l = 0; l < " <> showT kk <> "; l++) acc += " <> buf a <> "[i * " <> showT kk <> " + l] * " <> buf b <> "[l * " <> showT n <> " + j];",
        "    " <> out <> "[i * " <> showT n <> " + j] = acc;",
        "  }",
        "}"
      ]
    body (TransposeK a m n) =
      [ "for (long i = 0; i < " <> showT m <> "; i++) {",
        "  for (long j = 0; j < " <> showT n <> "; j++) " <> out <> "[j * " <> showT m <> " + i] = " <> buf a <> "[i * " <> showT n <> " + j];",
        "}"
      ]
    body (ConcatK a b outer ba bb) =
      [ "for (long o = 0; o < " <> showT outer <> "; o++) {",
        "  for (long j = 0; j < " <> showT ba <> "; j++) " <> out <> "[o * " <> showT (ba + bb) <> " + j] = " <> buf a <> "[o * " <> showT ba <> " + j];",
        "  for (long j = 0; j < " <> showT bb <> "; j++) " <> out <> "[o * " <> showT (ba + bb) <> " + " <> showT ba <> " + j] = " <> buf b <> "[o * " <> showT bb <> " + j];",
        "}"
      ]
    body (SliceK a outer blockIn from count) =
      [ "for (long o = 0; o < " <> showT outer <> "; o++) {",
        "  for (long j = 0; j < " <> showT count <> "; j++) " <> out <> "[o * " <> showT count <> " + j] = " <> buf a <> "[o * " <> showT blockIn <> " + " <> showT from <> " + j];",
        "}"
      ]

describe :: Kernel -> Text
describe (Elementwise n _) = "elementwise, " <> showT n <> " elements"
describe (MatMulK _ _ m k n) = "matmul " <> showT m <> "x" <> showT k <> " by " <> showT k <> "x" <> showT n
describe (TransposeK _ m n) = "transpose " <> showT m <> "x" <> showT n
describe (ConcatK _ _ o a b) = "concat " <> showT o <> " blocks of " <> showT a <> " + " <> showT b
describe (SliceK _ o bi f c) = "slice " <> showT o <> " blocks of " <> showT bi <> ", " <> showT c <> " from " <> showT f

ew :: Ew -> Text
ew (Load b) = buf b <> "[i]"
ew (EwAdd x y) = "(" <> ew x <> " + " <> ew y <> ")"
ew (EwMul x y) = "(" <> ew x <> " * " <> ew y <> ")"

buf :: Buf -> Text
buf (InBuf i) = "in" <> showT i
buf (TmpBuf i) = "t" <> showT i

kernelSize :: Kernel -> Int
kernelSize (Elementwise n _) = n
kernelSize (MatMulK _ _ m _ n) = m * n
kernelSize (TransposeK _ m n) = m * n
kernelSize (ConcatK _ _ o a b) = o * (a + b)
kernelSize (SliceK _ o _ _ c) = o * c

checkProgram :: Program -> Either Text ()
checkProgram p = do
  mapM_ (\(name, n) -> nonNegative ("input " <> name) [n]) (progInputs p)
  zipWithM_ checkKernel [0 ..] (progKernels p)
  where
    checkKernel i k = do
      let at = "kernel " <> showT i <> ": "
          needs b n = do
            size <- bufSize p i b
            unless (size == n) $
              Left (at <> buf b <> " has " <> showT size <> " elements, the kernel reads " <> showT n)
      nonNegative at (fields k)
      case k of
        Elementwise n e -> mapM_ (`needs` n) (loads e)
        MatMulK a b m kk n -> needs a (m * kk) >> needs b (kk * n)
        TransposeK a m n -> needs a (m * n)
        ConcatK a b o ba bb -> needs a (o * ba) >> needs b (o * bb)
        SliceK a o bi f c -> do
          needs a (o * bi)
          unless (f + c <= bi) $ Left (at <> "slice from " <> showT f <> " count " <> showT c <> " exceeds the block of " <> showT bi)
    fields (Elementwise n _) = [n]
    fields (MatMulK _ _ m k n) = [m, k, n]
    fields (TransposeK _ m n) = [m, n]
    fields (ConcatK _ _ o a b) = [o, a, b]
    fields (SliceK _ o bi f c) = [o, bi, f, c]
    loads (Load b) = [b]
    loads (EwAdd x y) = loads x <> loads y
    loads (EwMul x y) = loads x <> loads y

nonNegative :: Text -> [Int] -> Either Text ()
nonNegative at ns = unless (all (>= 0) ns) $ Left (at <> "negative size or offset in " <> showT ns)

bufSize :: Program -> Int -> Buf -> Either Text Int
bufSize p _ (InBuf j)
  | (_, n) : _ <- drop j (progInputs p), j >= 0 = Right n
  | otherwise = Left ("no input " <> showT j)
bufSize p i (TmpBuf j)
  | j >= i || j < 0 = Left (buf (TmpBuf j) <> " is read before it is written")
  | k : _ <- drop j (progKernels p) = Right (kernelSize k)
  | otherwise = Left ("no kernel " <> showT j)

showT :: (Show a) => a -> Text
showT = T.pack . show
